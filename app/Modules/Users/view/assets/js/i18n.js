function changeLanguage(lang) {
    localStorage.setItem('lang', lang);
    applyLanguage(lang);
}

function applyLanguage(lang) {
    const dict = translations[lang] || translations['fr'];
    
    // Set HTML attributes
    document.documentElement.lang = lang;
    if (lang === 'ar') {
        document.documentElement.dir = 'rtl';
        document.body.classList.add('rtl-mode');
    } else {
        document.documentElement.dir = 'ltr';
        document.body.classList.remove('rtl-mode');
    }

    // Translate all elements with data-i18n attribute
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key]) {
            // Check if element is an input with placeholder
            if (el.tagName === 'INPUT' && el.hasAttribute('placeholder') && el.getAttribute('type') !== 'submit' && el.getAttribute('type') !== 'button') {
                // If it's just a placeholder, we might want to translate labels instead, but if we marked an input:
                // Actually it's better to translate labels and buttons innerHTML
            }
            
            // Just replace innerText or HTML, but preserve nested HTML if needed.
            // For buttons and spans, textContent is usually safe.
            el.innerHTML = dict[key];
        }
    });

    // Update placeholders manually if needed
    const placeholders = document.querySelectorAll('[data-i18n-placeholder]');
    placeholders.forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (dict[key]) {
            el.setAttribute('placeholder', dict[key]);
        }
    });

    // Update select dropdown to match current language
    const langSelects = document.querySelectorAll('.lang-switcher select');
    langSelects.forEach(select => {
        select.value = lang;
    });
}

// Auto-apply on load
document.addEventListener('DOMContentLoaded', () => {
    const savedLang = localStorage.getItem('lang') || 'fr';
    applyLanguage(savedLang);
});
